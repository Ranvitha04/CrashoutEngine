		// Resolver Logic
		std::string ResolvePath(const std::string& relativePath) {

			// Clean up leading slashes just in case
			std::string cleanPath = relativePath;
			if (!cleanPath.empty() && (cleanPath[0] == '/' || cleanPath[0] == '\\')) {
				cleanPath = cleanPath.substr(1);
			}

			// A. Check Game Project first (Game overrides Engine)
			fs::path gameP = fs::path(gameAssetPath) / cleanPath;
			if (fs::exists(gameP)) return gameP.generic_string();

			// B. Check Core Engine assets second
			fs::path coreP = fs::path(coreAssetPath) / cleanPath;
			if (fs::exists(coreP)) return coreP.generic_string();

			// C. Fallback for missing images/sprites
			if (cleanPath.find("images/") == 0 || cleanPath.find("spritesheet/") == 0) {
				fs::path missingP = fs::path(coreAssetPath) / "images/missing.png";
				if (fs::exists(missingP)) return missingP.generic_string();
			}

			// D. Complete Failure
			std::cerr << "[AssetManager] ERROR: Asset not found in Game or Core: " << cleanPath << "\n";
			return "";
		}

		AssetManager::AssetManager() {

			// --- RUNTIME DETECTION ---
#if USE_IMGUI_EDITOR
			// Editor mode must always use the selected project asset tree for game assets.
			// Otherwise save writes to GetGameRoot() while reload may read from local build assets.
			{
				std::string rawPath = TOSTRING(ENGINE_CORE_ASSETS_PATH);
				if (rawPath.size() >= 2 && rawPath.front() == '"' && rawPath.back() == '"') {
					rawPath = rawPath.substr(1, rawPath.size() - 2);
				}
				coreAssetPath = rawPath;
				gameAssetPath = GetGameRoot() + "/assets/";
			}
#else
			if (std::filesystem::exists("core-assets")) {
				// STANDALONE MODE: Local folders next to the .exe
				coreAssetPath = "core-assets/";
				gameAssetPath = "assets/";
			}
			else {
				// EDITOR MODE: Use CMake absolute paths
				std::string rawPath = TOSTRING(ENGINE_CORE_ASSETS_PATH);
				if (rawPath.size() >= 2 && rawPath.front() == '"' && rawPath.back() == '"') {
					rawPath = rawPath.substr(1, rawPath.size() - 2);
				}
				coreAssetPath = rawPath;
				gameAssetPath = GetGameRoot() + "/assets/";
			}
#endif

			assetManifestPath = gameAssetPath + "json/assetmanifest.json";

			// Load FT_Library
			if (FT_Init_FreeType(&ftLibrary)) {
				std::cerr << "ERROR::FREETYPE: Could not init FreeType library" << std::endl;
			}

			// Start background loader thread
			loaderThread = std::thread(&AssetManager::LoaderThreadLoop, this);
		}

		AssetManager::~AssetManager() {
			// Final exit signal
			exitThread = true;
			condition.notify_all();
			if (loaderThread.joinable()) loaderThread.join();

			// Final FreeType cleanup
			if (ftLibrary) {
				FT_Done_FreeType(ftLibrary);
				ftLibrary = nullptr;
			}
		}

		void AssetManager::Shutdown() {
			// 1. Signal background thread to exit
			exitThread = true;
			condition.notify_all();
			if (loaderThread.joinable()) loaderThread.join();

			// 2. Selective Wipe: Remove only Game assets
			// We use an iterator because we are deleting while looping
			for (auto it = assets.begin(); it != assets.end(); ) {
				// If it's NOT a core asset, delete it
				if (!it->second->IsCore()) {
					it = assets.erase(it);
				}
				else {
					++it;
				}
			}

			// 3. Rebuild the Name Map
			// We wipe the name map and repopulate it only with the surviving core assets
			assetNames.clear();
			for (auto const& [id, asset] : assets) {
				assetNames[asset->GetName()] = id;
			}

			// 4. Restart the loader thread for the new project
			exitThread = false;
			loaderThread = std::thread(&AssetManager::LoaderThreadLoop, this);

			std::cout << "[AssetManager] Game assets cleared. Core engine assets preserved.\n";
		}

		void AssetManager::EnqueueLoad(const std::string& name, const std::string& path, AssetType type) {
			{
				std::lock_guard<std::mutex> lock(queueMutex);
				loadQueue.push({ name, path, type });
			}
			condition.notify_one();
		}

		void AssetManager::Update() {
			while (true) {
				std::pair<std::string, std::unique_ptr<IAsset>> completed;
				bool hasAsset = false;

				{
					std::lock_guard<std::mutex> lock(queueMutex);
					if (!completedQueue.empty()) {
						completed = std::move(completedQueue.front());
						completedQueue.pop();
						hasAsset = true;
					}
				}

				if (!hasAsset) break;

				std::string& name = completed.first;
				std::unique_ptr<IAsset>& asset = completed.second;

				// Finalize asset on main thread (GPU uploads etc)
				if (asset) {
					TextureAsset* tex = dynamic_cast<TextureAsset*>(asset.get());
					if (tex) {
						if (tex->UploadToGPU()) {
							tex->SetState(AssetState::Loaded);
							std::cout << "[AssetManager] Async load completed: " << name << std::endl;
						}
						else {
							tex->SetState(AssetState::Failed);
							std::cerr << "[AssetManager] Async GPU upload FAILED: " << name << std::endl;
						}
					}
					// Add other asset types as needed
					else {
						asset->SetState(AssetState::Loaded);
						std::cout << "[AssetManager] Async load completed (no GPU step): " << name << std::endl;
					}

					Load(name, std::move(asset), asset->GetPath());
				}
			}
		}

		void AssetManager::LoaderThreadLoop() {
			while (!exitThread) {
				LoadJob job;
				{
					std::unique_lock<std::mutex> lock(queueMutex);
					condition.wait(lock, [this] { return !loadQueue.empty() || exitThread; });

					if (exitThread && loadQueue.empty()) {
						break;
					}

					if (!loadQueue.empty()) {
						job = std::move(loadQueue.front());
						loadQueue.pop();
					}
					else {
						continue;
					}
				}

				std::unique_ptr<IAsset> loadedAsset = nullptr;

				switch (job.type) {
				case AssetType::Texture:
				case AssetType::SpriteSheet:
					loadedAsset = TextureAsset::Create(job.path);
					break;
				case AssetType::Scene:
					loadedAsset = SceneAsset::Create(job.path);
					break;
				case AssetType::TileMap:
					loadedAsset = TileMapAsset::Create(job.path);
					break;
				case AssetType::Font:
					// FontAsset::Create currently does OpenGL calls, needs refactoring
					// For now, let's skip or implement synchronously if needed
					break;
				// Add other cases...
				default:
					break;
				}

				if (loadedAsset) {
					loadedAsset->path = job.path;

					loadedAsset->SetState(AssetState::Loading);
					{
						std::lock_guard<std::mutex> lock(queueMutex);
						completedQueue.push({ job.name, std::move(loadedAsset) });
					}
				}
				else {
					std::cerr << "[AssetManager] Background load FAILED: " << job.name << " (" << job.path << ")" << std::endl;
				}
			}
		}

